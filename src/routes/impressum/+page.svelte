	<h2>Deine Daten bleiben bei dir</h2>
	<p>
		Alle Vokabeln, dein Lernfortschritt (Fächer, Zähler) und die Aussprache-Aufnahmen werden
		<strong>ausschließlich lokal in diesem Browser</strong> gespeichert (IndexedDB). Es gibt keinen Server dieser App, keine
		Anmeldung, keine Cookies und kein Tracking.
	</p>
	<p>
		Wenn du Websitedaten oder den Browserverlauf „inklusive Website-Daten“ löschst, den privaten Modus nutzt oder das Gerät
		wechselst, sind die Vokabeln weg. Nutze deshalb regelmäßig <em>Sicherung speichern</em> auf der Seite einer Sprache – die
		Datei kannst du jederzeit (auch auf einem anderen Gerät) wieder laden.
	</p>

	<h2>Abfragen bei Wikimedia</h2>
	<p>
		Nur beim <em>Hinzufügen</em> von Vokabeln fragt dein Browser direkt die öffentlichen Dienste der Wikimedia Foundation ab
		(de.wiktionary.org, commons.wikimedia.org, upload.wikimedia.org). Dabei werden das eingegebene Wort und – technisch
		bedingt – deine IP-Adresse an Wikimedia übermittelt. Es gilt die
		<a href="https://foundation.wikimedia.org/wiki/Policy:Privacy_policy/de" rel="noopener" target="_blank">Datenschutzrichtlinie der Wikimedia Foundation</a>.
		Das Abfragen der Vokabeln funktioniert danach komplett offline.
	</p>
